"""Pack icons into 1024x1024 atlases (8x8 cells of 128px) and write atlases/atlas.json.

One atlas = one upload and one draw batch. Use ImageRectOffset/ImageRectSize at runtime.
"""
import json
import os
import sys
from PIL import Image

sys.path.insert(0, os.path.dirname(__file__))
from tex_common import ROOT  # noqa

CELL, GRID = 128, 8
PER = GRID * GRID


def pack(keys, src_key, prefix):
    sheets, entries = {}, {}
    for si in range(0, len(keys), PER):
        chunk = keys[si:si + PER]
        name = f"{prefix}_{si // PER + 1}.png"
        img = Image.new("RGBA", (CELL * GRID, CELL * GRID), (0, 0, 0, 0))
        for i, k in enumerate(chunk):
            x, y = (i % GRID) * CELL, (i // GRID) * CELL
            img.alpha_composite(Image.open(os.path.join(ROOT, "icons", src_key(k))).convert("RGBA"), (x, y))
            entries[k] = dict(sheet=name, rect=[x, y, CELL, CELL])
        img.save(os.path.join(ROOT, "atlases", name), optimize=True)
        sheets[name] = dict(size=[CELL * GRID, CELL * GRID], count=len(chunk))
    return sheets, entries


def main():
    os.makedirs(os.path.join(ROOT, "atlases"), exist_ok=True)
    rep = json.load(open(os.path.join(ROOT, "icons", "_report.json")))
    keys = sorted(rep)
    s1, e1 = pack(keys, lambda k: rep[k]["plated"], "icons_plated")
    s2, e2 = pack(keys, lambda k: rep[k]["glyph"], "icons_glyph")
    out = dict(cell=CELL, sheets={**s1, **s2},
               icons={k: dict(plated=e1[k], glyph=e2[k]) for k in keys})
    # validator expects icons[k] to have "rect": flatten both for its bounds check
    flat = {}
    for k in keys:
        flat[f"{k}#plated"] = e1[k]
        flat[f"{k}#glyph"] = e2[k]
    out["icons_flat"] = flat
    with open(os.path.join(ROOT, "atlases", "atlas.json"), "w") as f:
        json.dump(out, f, indent=1)
    lines = ["--!strict", "-- GENERATED by _generators/build_atlases.py. Do not edit.", "export type Cell = { sheet: string, x: number, y: number }",
             "export type Entry = { plated: Cell, glyph: Cell }", "local data: { cell: number, icons: { [string]: Entry } } = {", "\tcell = %d," % CELL, "\ticons = {"]
    for k in keys:
        a, b = e1[k], e2[k]
        lines.append('\t\t["%s"] = { plated = { sheet = "atlases/%s", x = %d, y = %d }, glyph = { sheet = "atlases/%s", x = %d, y = %d } },'
                     % (k, a["sheet"], a["rect"][0], a["rect"][1], b["sheet"], b["rect"][0], b["rect"][1]))
    lines += ["\t},", "}", "", "return table.freeze(data)", ""]
    os.makedirs(os.path.join(ROOT, "luau"), exist_ok=True)
    with open(os.path.join(ROOT, "luau", "AtlasData.luau"), "w") as f:
        f.write("\n".join(lines))
    print(len(keys), "icons ->", len(out["sheets"]), "atlas sheets")


if __name__ == "__main__":
    main()
